// Native startup artwork, using our puppet vector and a small original arcade wordmark.
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {flattenPath,transformPoint} from './icon-geometry.mjs';
const root='android/app/src/main/res',letters={
 F:['11111','10000','10000','11110','10000','10000','10000'],
 I:['11111','00100','00100','00100','00100','00100','11111'],
 N:['10001','11001','11001','10101','10011','10011','10001'],
 G:['01111','10000','10000','10111','10001','10001','01111'],
 E:['11111','10000','10000','11110','10000','10000','11111'],
 R:['11110','10001','10001','11110','10100','10010','10001'],
 H:['10001','10001','10001','11111','10001','10001','10001'],
 T:['11111','00100','00100','00100','00100','00100','00100']
};
let namePath='',cursor=0;
for(const ch of 'FINGER FIGHT'){
 if(ch===' '){cursor+=4;continue;}
 for(let y=0;y<7;y++)for(let x=0;x<5;x++)if(letters[ch][y][x]==='1')namePath+=`M${cursor+x} ${y} L${cursor+x+1} ${y} L${cursor+x+1} ${y+1} L${cursor+x} ${y+1} Z `;
 cursor+=6;
}
const width=cursor-1,xml=(w,h,body)=>`<?xml version="1.0" encoding="utf-8"?>\n<!-- Finger Fight startup artwork; generated by tools/startup-art.mjs. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="${w}dp" android:height="${h}dp" android:viewportWidth="${w}" android:viewportHeight="${h}">${body}</vector>\n`;
const name=(x,y,sx,sy)=>`<group android:translateX="${x}" android:translateY="${y}" android:scaleX="${sx}" android:scaleY="${sy}"><path android:pathData="${namePath}" android:fillColor="#fbbf24"/></group>`;
const puppet=readFileSync(`${root}/drawable/puppet_cartoon_5.xml`,'utf8').match(/<vector[^>]*>([\s\S]*)<\/vector>/)[1];
const legacy=xml(108,108,`<group android:translateX="15.12" android:translateY="6.12" android:scaleX="0.72" android:scaleY="0.72">${puppet}</group>`+name(32,71.5,44/width,.9));
const branding=xml(200,80,name(10,26,180/width,4));
writeFileSync(`${root}/drawable/startup_mark.xml`,legacy);writeFileSync(`${root}/drawable/startup_name.xml`,branding);
// Review uses the same vector paths/matrices, flattened only for the dependency-free raster tool.
const mul=(m,n)=>[m[0]*n[0]+m[2]*n[1],m[1]*n[0]+m[3]*n[1],m[0]*n[2]+m[2]*n[3],m[1]*n[2]+m[3]*n[3],m[0]*n[4]+m[2]*n[5]+m[4],m[1]*n[4]+m[3]*n[5]+m[5]],f=n=>Number(n.toFixed(4));
function review(source,base){
 let m=base,stack=[],svg='';
 for(const token of source.matchAll(/<group\b[^>]*>|<\/group>|<path\b[^>]*\/>/g)){
  const tag=token[0],a=Object.fromEntries([...tag.matchAll(/android:(\w+)="([^"]*)"/g)].map(x=>[x[1],x[2]]));
  if(tag.startsWith('</')){m=stack.pop();continue;}
  if(tag.startsWith('<group')){stack.push(m);const r=Number(a.rotation||0)*Math.PI/180,c=Math.cos(r),s=Math.sin(r),sx=Number(a.scaleX||1),sy=Number(a.scaleY||1);m=mul(m,[c*sx,s*sx,-s*sy,c*sy,Number(a.translateX||0),Number(a.translateY||0)]);continue;}
  const d=flattenPath(a.pathData).map(path=>path.map((p,i)=>{const q=transformPoint(m,p);return`${i?'L':'M'}${f(q[0])} ${f(q[1])}`;}).join(' ')).join(' ');
  const paint=(key,alpha)=>{let color=a[key]||'#00000000',opacity=Number(a[alpha]??1);if(color.length===9){opacity*=parseInt(color.slice(1,3),16)/255;color='#'+color.slice(3);}return{color,opacity};};
  const fill=paint('fillColor','fillAlpha'),stroke=paint('strokeColor','strokeAlpha');
  if(fill.opacity)svg+=`<path d="${d}" fill="${fill.color}" opacity="${fill.opacity}"/>`;
  if(stroke.opacity&&Number(a.strokeWidth))svg+=`<path d="${d}" fill="none" stroke="${stroke.color}" stroke-width="${f(Number(a.strokeWidth)*Math.sqrt(Math.abs(m[0]*m[3]-m[1]*m[2])))}" opacity="${stroke.opacity}"/>`;
 }
 return svg;
}
mkdirSync('artifacts',{recursive:true});
const svg='<svg xmlns="http://www.w3.org/2000/svg" width="1000" height="750"><rect width="1000" height="750" fill="#0b1020"/>'+review(legacy,[3.6,0,0,3.6,55.6,105.6])+review('<vector>'+puppet+'</vector>',[3.6,0,0,3.6,555.6,105.6])+review(branding,[1.5,0,0,1.5,600,580])+'</svg>\n';
writeFileSync('artifacts/startup-review.svg',svg);
console.log('Generated puppet/name legacy splash and 200×80dp Android branding wordmark.');
